/**
 * Playstyle presets — curated tech ratings per playstyle.
 *
 * Ratings are EDITORIAL, path-relative guidance for new players:
 *   S — cornerstone of this playstyle; pick it as soon as you can
 *   A — strong pick that supports the path
 *   B — situational / late-game support for this playstyle
 *
 * Ratings only appear while a preset is selected (the user "chooses a path"),
 * and every key must exist in techtree.json (validated by
 * scripts/check_presets.py at build time).
 */

export type PresetRating = "S" | "A" | "B";

export interface PlaystylePreset {
  id: string;
  name: string;
  /** short one-liner shown under the preset name */
  tagline: string;
  /** accent color for pills / chips */
  color: string;
  /** lucide icon key rendered by PresetBar */
  icon: string;
  /** DLC the signature techs come from (informational) */
  dlcNote?: string;
  /** tech key -> rating for this path */
  ratings: Record<string, PresetRating>;
}

