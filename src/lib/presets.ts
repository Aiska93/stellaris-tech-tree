/** id -> preset */
export const PRESET_BY_ID: ReadonlyMap<string, PlaystylePreset> = new Map(
  PLAYSTYLE_PRESETS.map((p) => [p.id, p]),
);

/** precomputed Map per preset (module-level, zero per-render cost) */
const RATINGS_CACHE = new Map<string, ReadonlyMap<string, PresetRating>>(
  PLAYSTYLE_PRESETS.map((p) => [p.id, new Map(Object.entries(p.ratings))]),
);

export function presetRatingsMap(
  id: string | null,
): ReadonlyMap<string, PresetRating> | null {
  if (!id) return null;
  return RATINGS_CACHE.get(id) ?? null;
}

export function ratingOf(
  id: string | null,
  techKey: string,
): PresetRating | null {
  return presetRatingsMap(id)?.get(techKey) ?? null;
}
